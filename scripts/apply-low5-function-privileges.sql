-- ============================================================================
-- 低-5 是正：新しく作る関数（RPC）に anon の実行権限が自動で付かないようにする
--
-- 【使い方】
--   Supabase の SQL Editor に、このファイルの中身を丸ごと貼り付けて「Run」。
--   staging → 本番 の順に実行してください。
--
-- 【何をするか】
--   PostgreSQL は CREATE FUNCTION 時に EXECUTE 権限を PUBLIC へ自動付与します。
--   Supabase では PostgREST 経由で anon（＝利用者のブラウザが持つ鍵）から RPC を呼べるため、
--   対策しないと「新しく作った関数を誰でも直接呼べる」状態になります。
--
--   実際に consume_signup_attempt がこの状態で、戻り値に code_hash を含んでいたため、
--   anon キーからハッシュを取得して6桁の確認コードをオフラインで総当たりできる経路が
--   存在しました（2026-08-09 発見・個別に塞ぎ済み）。
--
--   個別の revoke は「関数を作るたびに書き足す」手作業に依存しており、
--   忘れれば同じ穴が再発します。この設定はその再発を構造的に防ぎます。
--
-- 【影響範囲】
--   ・既存の関数には影響しません（既定権限は「これから作られるもの」にのみ適用）
--   ・アプリの動作は変わりません（サーバーは service_role で接続するため）
--   ・以後、anon から呼ばせたい関数がある場合のみ、明示的に grant してください
--
-- 【安全性】
--   既存データ・既存関数・アプリの挙動を一切変更しません。
--   何度実行しても同じ結果になります（冪等）。
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 手順1：適用
-- ----------------------------------------------------------------------------
alter default privileges for role postgres in schema public
  revoke all on functions from anon, authenticated;


-- ----------------------------------------------------------------------------
-- 手順2：確認（読み取り専用）
-- ----------------------------------------------------------------------------
-- 【期待する結果】
--   「関数の既定権限」の行の判定が OK になること。
--   （テーブル側は本番反映時に設定済みなので、こちらも OK のはずです）
--
-- 【結果の読み方】
--   判定が「要確認」の場合、手順1が正しく実行されていない可能性があります。
--   その場合は手順1をもう一度実行してから、この確認を再実行してください。
select
  '関数の既定権限' as "確認内容",
  case when count(*) = 0 then 'OK' else '要確認' end as "判定",
  'postgres作成時にanon等へ自動付与する設定: ' || count(*)::text
    || ' 件（期待: 0 件）' as "詳細"
from pg_default_acl d
join pg_namespace ns on ns.oid = d.defaclnamespace
where ns.nspname = 'public'
  and d.defaclobjtype = 'f'          -- f = 関数
  and d.defaclrole = 'postgres'::regrole
  and (array_to_string(d.defaclacl, ',') like '%anon=%'
    or array_to_string(d.defaclacl, ',') like '%authenticated=%');


-- ============================================================================
-- 【補足】supabase_admin の行について
--
-- pg_default_acl には supabase_admin が設定した行も存在し、そちらには anon が残ります。
-- これは以下の理由で対処不要かつ対処不能です（テーブル側と同じ事情）。
--   ・既定権限は「その関数を誰が作ったか」で決まる。SQL Editor で作れば作成者は postgres
--   ・supabase_admin は Supabase 内部専用の役割で、利用者が関数を作る際には使われない
--   ・supabase_admin の既定権限は権限不足で変更できない（permission denied）
-- そのため上の確認は postgres の行だけを judge しています。
-- ============================================================================
